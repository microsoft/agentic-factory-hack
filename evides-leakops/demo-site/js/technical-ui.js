  // The source wraps its prompts at about 120 characters. For reading, continuation lines are joined to their paragraph or bullet;
  // the copy button still copies the original text.
  function reflow(text) {
    const out = [];
    for (const raw of text.split('\n')) {
      const line = raw.trimEnd();
      const startsItem = /^\s*([-*]|\d+\.)\s/.test(line);
      if (!line.trim()) out.push('');
      else if (!out.length || out[out.length - 1] === '' || startsItem) out.push(line);
      else out[out.length - 1] += ' ' + line.trim();
    }
    return out.join('\n');
  }

