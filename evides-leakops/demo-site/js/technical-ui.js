  /* ---------- public API ---------- */
  function panel(slide, tab, lang) {
    const kind = kindOf(slide.id);
    if (kind === 'alarm') return alarmPanel(tab, lang);
    if (kind === 'trust') return trustPanel(tab, lang);
    if (tab === 1) return instructions(slide.id, lang);
    if (tab === 2) return tools(slide.id, lang);
    if (tab === 3) return data(slide.id, lang);
    if (tab === 4) return rulesPanel(slide.id, lang);
    return sourcePanel(sourceRows(slide.id), lang);
  }
  // overview is a function, so it is only built when that tab is open
  function wrap(slide, ctx, tab, overview) {
    const kind = kindOf(slide.id);
    if (!kind) return overview();
    const body = tab === 0 ? overview() : `<div class="tpanel">${panel(slide, tab, ctx.lang)}</div>`;
    return `${tabbar(kind, tab, ctx.lang)}<div class="tbody" role="tabpanel">${body}</div>`;
  }
  window.TechUI = { wrap, tabCount: 6, instructionText: key => TECH.agents[key].instructions.text };
