  function sourceRows(id) {
    const key = AGENT_KEY[id], a = TECH.agents[key], rows = [];
    const add = (group, lbl, r) => rows.push({ group, lbl, r });
    add('Agent', a.name + ' (class)', a.classRef); add('Agent', 'AgentSpec', a.spec); add('Agent', 'Instructions', a.instructions); add('Agent', 'AllowedTools', a.allowedToolsRef);
    add('Schema', a.answerType.name, a.answerType); if (a.resultType) add('Schema', a.resultType.name, a.resultType);
    a.rules.forEach(r => r.classes.forEach(c => add('Code rules', c.name, c)));
    a.ruleCalls.forEach(c => add('Code rules', 'applied: ' + c.call, c));
    a.tools.forEach(x => add('MCP tools', x.name, x));
    a.containers.forEach(c => { add('Data', c.name + ' (container)', c); if (c.file) add('Data', c.name + ' (seed file)', c.file); if (c.generator) add('Data', c.name + ' (generator)', c.generator); });
    if (a.writes) a.writes.forEach(c => add('Data', c.name + ' (written)', c));
    if (a.external) add('External', a.external.label, a.external);
    TECH.mcp.registry.forEach((r, i) => add('Foundry registration', ['MCP tool + allow-list', 'strict answer schema', 'definition hash'][i], r));
    add('Foundry registration', 'project connection leakops-mcp', TECH.mcp.connection);
    if (a.knowledge) {
      const kb = kbOf(a);
      add('Knowledge', 'knowledge paragraph in the instructions', a.knowledge.instructions); add('Knowledge', 'AgentSpec.Knowledge', a.knowledge.spec);
      add('Knowledge', 'MCP tool leakops_kb (registry)', TECH.knowledge.registry.tool);
      add('Knowledge', kb.name + ' (knowledge base)', kb.definition); add('Knowledge', kb.source + ' (knowledge source)', kb.sourceDefinition); add('Knowledge', kb.connection + ' (connection)', kb.connectionRef);
      kb.docs.forEach(d => add('Knowledge documents', d.code, d));
    }
    a.skills.forEach(n => { const s = TECH.skills.items.find(x => x.name === n); add('Skills', n, s); });
    if (a.skills.length) add('Skills', 'injection into the instructions', a.skillsRef);
    return rows;
  }
